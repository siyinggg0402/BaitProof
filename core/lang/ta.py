"""Tamil scam knowledge: pattern strings only, the Tamil twin of ms.py and zh.py (the same names, so each block mirrors an English one in core/pipelines/check).
These patterns run only when the message is detected as Tamil (see core.lang.text.Dual). Written for the Tamil people actually read in Singapore, Malaysia, Tamil Nadu
and Sri Lanka, with brands and acronyms in Latin letters as they appear in real messages ("DBS", "OTP", "KYC", "WhatsApp").

Three things are different from the Latin-script packs:
  * Python's \\b does not work next to Tamil vowel signs and the virama (they are not word characters), so there is no \\b here. A Tamil stem is matched as a PREFIX, then
    T takes the rest of the word, so a quote is the whole word ("செலுத்துங்கள்", not "செலுத்"). B is a "not in the middle of a word" guard for short stems.
  * Tamil is agglutinative and verb-final, and its "don't" comes AFTER the verb ("பகிர வேண்டாம்" = "don't share"; "பகிராதீர்கள்" = "don't share" too). So the ask
    patterns carry their own look-ahead (NOT) and a list of imperative endings (IMP), instead of the "never/don't ... " look-behind the English ones use.
  * Latin tokens inside Tamil text ("OTP-ஐ", "WhatsApp-இல்") are matched with the L() guard, which only refuses neighbouring Latin letters.
The Tamil text of this project is ours (written with an AI assistant) and has not been reviewed by a native speaker; docs/TAMIL.md says what to check first."""
from __future__ import annotations


def J(*alts: str) -> str:
    return "|".join(alts)


S = r"[^.!?\n]"  # inside one sentence
T = r"[஀-௿]*"  # the rest of a Tamil word (its case endings and verb endings)
B = r"(?<![஀-௿])"  # not in the middle of a Tamil word


def w(*stems: str) -> str:
    """A Tamil word that starts with one of these stems, taken whole."""
    return B + "(?:" + "|".join(stems) + ")" + T


def L(*words: str) -> str:
    """Latin words (brands, OTP, KYC ...) that are not part of a longer Latin word."""
    return r"(?<![A-Za-z])(?:" + "|".join(words) + r")(?![A-Za-z])"


NEGEND = r"(?![\u0b80-\u0bff]{0,2}ா(?:தீ|தே|மல்|த ?வாறு))"  # a stem followed by -ாதீர்/-ாதே is the negative form ("பகிராதீர்கள்", "செலுத்தாதீர்கள்" = don't ...): not a request


def V(*stems: str) -> str:
    """A verb that starts a Tamil word (so "சொல்ல" is not found inside "கடவுச்சொல்லை"), is not the negative form, and is taken whole."""
    return B + "(?:" + "|".join(stems) + ")" + NEGEND + T


