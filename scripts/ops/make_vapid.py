"""Make the site's VAPID keys for Web Push (the "a friend just passed you" notifications) and add them to .env.

    python -m scripts.ops.make_vapid

It writes VAPID_PRIVATE_KEY, VAPID_PUBLIC_KEY and VAPID_SUBJECT to .env only if they are not there yet, and never prints the private key.
.env is git-ignored. Set VAPID_SUBJECT to a mailto: or https: address you control (push services use it to contact the operator)."""
from __future__ import annotations

import base64
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from py_vapid import Vapid

ENV = Path(".env")


def b64(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()


def main() -> int:
    text = ENV.read_text(encoding="utf-8") if ENV.exists() else ""
    values = {}
    for line in text.splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, _, val = line.partition("=")
            values[key.strip()] = val.split("#", 1)[0].strip()
    if values.get("VAPID_PRIVATE_KEY") and values.get("VAPID_PUBLIC_KEY"):
        print("VAPID keys are already in .env: nothing changed.")
        return 0
    v = Vapid()
    v.generate_keys()
    private = b64(v.private_key.private_numbers().private_value.to_bytes(32, "big"))
    public = b64(v.public_key.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint))
    lines = [l for l in text.splitlines() if not l.lstrip().startswith(("VAPID_PRIVATE_KEY=", "VAPID_PUBLIC_KEY="))]
    lines += ["", "# Web Push (friend notifications). Generated by scripts/ops/make_vapid.py; keep the private key secret.", f"VAPID_PRIVATE_KEY={private}", f"VAPID_PUBLIC_KEY={public}"]
    if "VAPID_SUBJECT" not in values:
        lines.append("VAPID_SUBJECT=mailto:you@example.com   # change to an address you control")
    ENV.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"VAPID keys written to .env (public key {public[:12]}...). The private key was not printed. Edit VAPID_SUBJECT to an address you control.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
